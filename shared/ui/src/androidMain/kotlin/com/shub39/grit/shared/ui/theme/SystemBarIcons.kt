package com.shub39.grit.shared.ui.theme

import android.app.Activity
import android.content.Context
import android.content.ContextWrapper
import androidx.compose.runtime.Composable
import androidx.compose.runtime.SideEffect
import androidx.compose.ui.platform.LocalInspectionMode
import androidx.compose.ui.platform.LocalView
import androidx.core.view.WindowCompat

/**
 * Sprout (#150): lets the status and navigation bar icons follow the app's chosen theme instead of
 * the phone's dark mode. `enableEdgeToEdge()` only looks at the system setting, so a light app
 * theme on a dark phone kept white icons on light paper.
 */
@Composable
internal fun SyncSystemBarIcons(isDark: Boolean) {
    if (LocalInspectionMode.current) return
    val view = LocalView.current
    SideEffect {
        val window = view.context.findActivity()?.window ?: return@SideEffect
        WindowCompat.getInsetsController(window, view).apply {
            isAppearanceLightStatusBars = !isDark
            isAppearanceLightNavigationBars = !isDark
        }
    }
}

private tailrec fun Context.findActivity(): Activity? =
    when (this) {
        is Activity -> this
        is ContextWrapper -> baseContext.findActivity()
        else -> null
    }
